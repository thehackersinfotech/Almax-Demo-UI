// Generic paginated wrapper
export function paginate<T>(items: T[], page = 1, pageSize = 20): { count: number; results: T[]; next: null; previous: null } {
  const start = (page - 1) * pageSize;
  return {
    count: items.length,
    results: items.slice(start, start + pageSize),
    next: null,
    previous: null,
  };
}
